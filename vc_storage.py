"""VOLLEY CONTROL storage. Set DATABASE_URL to persistent PostgreSQL in Streamlit secrets.

Without it, SQLite is a *temporary preview* on Community Cloud, not durable storage.
"""
import json
import os
from datetime import datetime, timezone
from sqlalchemy import create_engine, text
from sqlalchemy.exc import IntegrityError

RESULT_FIELDS = ("played", "home_sets", "away_sets", "sets")


def utcnow():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def open_engine(url=None):
    url = url or os.environ.get("DATABASE_URL") or "sqlite:////tmp/volley_control_preview.sqlite3"
    if url.startswith("postgres://"):
        url = url.replace("postgres://", "postgresql+psycopg://", 1)
    if url.startswith("postgresql://"):
        url = url.replace("postgresql://", "postgresql+psycopg://", 1)
    engine = create_engine(url, pool_pre_ping=True)
    with engine.begin() as cx:
        cx.execute(text("""CREATE TABLE IF NOT EXISTS games (
          game_key VARCHAR(220) PRIMARY KEY,
          source VARCHAR(32) NOT NULL,
          season VARCHAR(20) NOT NULL,
          official_json TEXT NOT NULL,
          overrides_json TEXT NOT NULL,
          created_at VARCHAR(40) NOT NULL,
          updated_at VARCHAR(40) NOT NULL)"""))
        cx.execute(text("""CREATE TABLE IF NOT EXISTS game_audit (
          id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
          game_key VARCHAR(220) NOT NULL,
          field VARCHAR(120) NOT NULL,
          old_value TEXT, new_value TEXT,
          actor VARCHAR(64) NOT NULL,
          changed_at VARCHAR(40) NOT NULL,
          note TEXT NOT NULL)""") if engine.dialect.name == "postgresql" else text("""CREATE TABLE IF NOT EXISTS game_audit (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          game_key VARCHAR(220) NOT NULL,
          field VARCHAR(120) NOT NULL,
          old_value TEXT, new_value TEXT,
          actor VARCHAR(64) NOT NULL,
          changed_at VARCHAR(40) NOT NULL,
          note TEXT NOT NULL)"""))
        cx.execute(text("""CREATE TABLE IF NOT EXISTS import_conflicts (
          game_key VARCHAR(220) NOT NULL,
          field VARCHAR(120) NOT NULL,
          incoming TEXT,
          detected_at VARCHAR(40) NOT NULL,
          PRIMARY KEY(game_key, field))"""))
    return engine


def effective(official, overrides):
    return {**official, **overrides}


def save_import(engine, games, only_results=False):
    """Saves real downloaded matches; does not clear organizer overrides.

    Both inserts and updates run in a DB transaction. If a user explicitly chose
    a different value, record the conflict rather than overwriting it.
    """
    counts = {"inserted": 0, "updated": 0, "unchanged": 0, "conflicts": 0}
    now = utcnow()
    with engine.begin() as cx:
        for game in games:
            key = game["game_key"]
            current = cx.execute(text("SELECT official_json, overrides_json FROM games WHERE game_key=:key"), {"key": key}).mappings().first()
            if current is None:
                if only_results:
                    continue  # Results refresh cannot create unknown matches.
                cx.execute(text("""INSERT INTO games
                  (game_key, source, season, official_json, overrides_json, created_at, updated_at)
                  VALUES (:key,:source,:season,:data,'{}',:now,:now)"""),
                  {"key": key, "source": game["source"], "season": game["season"], "data": json.dumps(game, ensure_ascii=False), "now": now})
                counts["inserted"] += 1
                continue
            prior = json.loads(current["official_json"])
            overrides = json.loads(current["overrides_json"])
            candidates = RESULT_FIELDS if only_results else game.keys()
            new_data = dict(prior)
            changed = False
            for field in candidates:
                if field not in game or field == "game_key":
                    continue
                if prior.get(field) == game[field]:
                    continue
                new_data[field] = game[field]
                changed = True
                if field in overrides and overrides[field] != game[field]:
                    cx.execute(text("""DELETE FROM import_conflicts WHERE game_key=:key AND field=:field"""),
                               {"key": key, "field": field})
                    cx.execute(text("""INSERT INTO import_conflicts(game_key,field,incoming,detected_at)
                      VALUES(:key,:field,:incoming,:at)"""),
                      {"key": key, "field": field, "incoming": json.dumps(game[field], ensure_ascii=False), "at": now})
                    counts["conflicts"] += 1
                elif field in overrides:
                    cx.execute(text("DELETE FROM import_conflicts WHERE game_key=:key AND field=:field"),
                               {"key": key, "field": field})
            if changed:
                cx.execute(text("UPDATE games SET official_json=:data, updated_at=:now WHERE game_key=:key"),
                           {"key": key, "data": json.dumps(new_data, ensure_ascii=False), "now": now})
                counts["updated"] += 1
            else:
                counts["unchanged"] += 1
    return counts


def list_games(engine):
    with engine.connect() as cx:
        rows = cx.execute(text("SELECT game_key, official_json, overrides_json FROM games")).mappings().all()
    return sorted((effective(json.loads(row["official_json"]), json.loads(row["overrides_json"]))
                   for row in rows), key=lambda g: (g.get("date", "9999"), g.get("time", "99:99"), g.get("game_number", "")))


def modify_game(engine, game_key, field, value, reason=""):
    if field in {"game_key", "official_id", "source", "season", "group_id", "our_team_id"}:
        raise ValueError("Gli identificativi tecnici non sono modificabili da questa schermata.")
    now = utcnow()
    with engine.begin() as cx:
        row = cx.execute(text("SELECT official_json, overrides_json FROM games WHERE game_key=:key"), {"key": game_key}).mappings().first()
        if not row:
            raise KeyError("Gara non trovata")
        official, overrides = json.loads(row["official_json"]), json.loads(row["overrides_json"])
        if field not in official:
            raise ValueError(f"Campo non previsto: {field}")
        previous = overrides.get(field, official.get(field))
        overrides[field] = value
        cx.execute(text("UPDATE games SET overrides_json=:data, updated_at=:now WHERE game_key=:key"),
                   {"key": game_key, "data": json.dumps(overrides, ensure_ascii=False), "now": now})
        cx.execute(text("""INSERT INTO game_audit(game_key,field,old_value,new_value,actor,changed_at,note)
          VALUES(:key,:field,:old,:new,'PATTY',:now,:reason)"""),
          {"key": game_key, "field": field, "old": json.dumps(previous, ensure_ascii=False),
           "new": json.dumps(value, ensure_ascii=False), "now": now, "reason": reason})


def audit_for_game(engine, key):
    with engine.connect() as cx:
        return cx.execute(text("""SELECT field,old_value,new_value,actor,changed_at,note
          FROM game_audit WHERE game_key=:key ORDER BY id DESC LIMIT 40"""), {"key": key}).mappings().all()


def conflicts_for_game(engine, key):
    with engine.connect() as cx:
        return cx.execute(text("""SELECT field,incoming,detected_at FROM import_conflicts
          WHERE game_key=:key ORDER BY field"""), {"key": key}).mappings().all()


def create_manual_game(engine, our_team, date, hour, opponent, is_home, venue,
                       address='', game_number='', category='', notes=''):
    # Explicit PATTY-only fallback, never presented as automatic FIPAV / PGS data.
    from uuid import uuid4
    from vc_core import parse_date, parse_time, SEASON
    if not opponent.strip():
        raise ValueError('Devi indicare la squadra avversaria.')
    game_id=uuid4().hex
    team_name=our_team['team_name']
    match={
        'game_key':'MANUAL:'+SEASON+':'+game_id,
        'source':'MANUAL', 'season':SEASON, 'group_id':'', 'official_id':game_id,
        'game_number':game_number.strip(), 'category':category.strip() or our_team['category'],
        'our_team_id':str(our_team['team_id']), 'our_team_name':team_name, 'is_home':bool(is_home),
        'home_team':team_name if is_home else opponent.strip(),
        'away_team':opponent.strip() if is_home else team_name,
        'date':parse_date(date), 'time':parse_time(hour),
        'venue':venue.strip() or 'Palestra non indicata', 'address':address.strip(),
        'played':False, 'home_sets':None, 'away_sets':None, 'sets':[], 'notes':notes.strip(),
        'required_referees':1 if is_home else 0,
        'required_scorers':1 if is_home else 0, 'hidden':False,
    }
    save_import(engine,[match])
    with engine.begin() as cx:
        cx.execute(text("""INSERT INTO game_audit(game_key,field,old_value,new_value,actor,changed_at,note)
          VALUES(:key,'created',NULL,:new,'PATTY',:now,'Inserimento manuale')"""),
          dict(key=match['game_key'],new=json.dumps(match,ensure_ascii=False),now=utcnow()))
    return match